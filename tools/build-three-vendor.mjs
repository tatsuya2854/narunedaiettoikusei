// ゲームで使う three.js の部品だけを1ファイルに束ねる（3Dモードのときだけ読み込まれる）。
// three を上げたら npm run vendor:three を流してコミットする。
import { build } from "esbuild";
import { readFileSync } from "node:fs";
const v = JSON.parse(readFileSync(new URL("../node_modules/three/package.json", import.meta.url))).version;
await build({
  stdin: {
    contents: `
      export { WebGLRenderer, Scene, PerspectiveCamera, HemisphereLight, DirectionalLight, AnimationMixer, LoopRepeat, LoopOnce,
        Box3, Vector3, Mesh, CircleGeometry, MeshBasicMaterial, CanvasTexture, SRGBColorSpace, Timer, Color } from "three";
      export { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
      export { MeshoptDecoder } from "three/examples/jsm/libs/meshopt_decoder.module.js";
      export const REVISION_VENDORED = ${JSON.stringify(v)};`,
    resolveDir: new URL("..", import.meta.url).pathname,
  },
  bundle: true, format: "esm", minify: true, target: ["safari15", "chrome100"],
  outfile: new URL("../3d/vendor/three-char.js", import.meta.url).pathname,
  banner: { js: `/* three.js r${v} (MIT) — subset for 3D character. generated by tools/build-three-vendor.mjs */` },
  legalComments: "none",
});
console.log("ok three", v);
